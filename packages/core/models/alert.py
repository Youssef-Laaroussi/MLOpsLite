"""SQLAlchemy models for multi-channel alert engine."""

import enum
from datetime import datetime

from sqlalchemy import (
    JSON,
    Boolean,
    DateTime,
    Float,
    ForeignKey,
    String,
    Text,
)
from sqlalchemy import (
    Enum as SAEnum,
)
from sqlalchemy.orm import Mapped, mapped_column

from packages.core.db.base import Base, TimestampMixin, UUIDMixin


class AlertSeverity(str, enum.Enum):
    """Alert severity classification."""

    INFO = "INFO"
    WARNING = "WARNING"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class AlertStatus(str, enum.Enum):
    """Alert lifecycle state."""

    OPEN = "OPEN"
    ACKNOWLEDGED = "ACKNOWLEDGED"
    RESOLVED = "RESOLVED"


class Alert(Base, UUIDMixin, TimestampMixin):
    """An incident or anomaly event generated by the monitoring system."""

    __tablename__ = "alerts"

    project_id: Mapped[str | None] = mapped_column(
        String(36), ForeignKey("projects.id", ondelete="SET NULL"), nullable=True, index=True
    )
    model_name: Mapped[str | None] = mapped_column(String(200), nullable=True, index=True)
    deployment_id: Mapped[str | None] = mapped_column(
        String(36), ForeignKey("deployments.id", ondelete="SET NULL"), nullable=True, index=True
    )
    event_type: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        doc="Event type: DATA_DRIFT, PERFORMANCE_DROP, CONTAINER_CRASH, LATENCY_SPIKE",
    )
    severity: Mapped[AlertSeverity] = mapped_column(
        SAEnum(AlertSeverity, name="alert_severity", create_constraint=True),
        default=AlertSeverity.WARNING,
        nullable=False,
    )
    title: Mapped[str] = mapped_column(String(300), nullable=False)
    message: Mapped[str] = mapped_column(Text, nullable=False)
    details_json: Mapped[dict | None] = mapped_column(
        JSON, nullable=True, doc="Metric scores, feature names, or stack traces"
    )
    status: Mapped[AlertStatus] = mapped_column(
        SAEnum(AlertStatus, name="alert_status", create_constraint=True),
        default=AlertStatus.OPEN,
        server_default="OPEN",
        nullable=False,
    )
    acknowledged_by: Mapped[str | None] = mapped_column(String(100), nullable=True)
    resolved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)


class AlertRule(Base, UUIDMixin, TimestampMixin):
    """Threshold rule evaluated against real monitoring metrics (metric OP threshold)."""

    __tablename__ = "alert_rules"

    name: Mapped[str] = mapped_column(String(200), nullable=False)
    metric: Mapped[str] = mapped_column(
        String(50), nullable=False, doc="drift_share | latency_p95_ms | failed_deployments"
    )
    operator: Mapped[str] = mapped_column(String(2), nullable=False, default=">")
    threshold: Mapped[float] = mapped_column(Float, nullable=False)
    model_name: Mapped[str | None] = mapped_column(
        String(200), nullable=True, doc="Scope; NULL means all models"
    )
    severity: Mapped[AlertSeverity] = mapped_column(
        SAEnum(AlertSeverity, name="alert_severity", create_constraint=True),
        default=AlertSeverity.WARNING,
        nullable=False,
    )
    enabled: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)


class NotificationChannel(Base, UUIDMixin, TimestampMixin):
    """Outbound webhook destination (Slack, Discord or generic HTTP)."""

    __tablename__ = "notification_channels"

    name: Mapped[str] = mapped_column(String(200), nullable=False)
    kind: Mapped[str] = mapped_column(String(20), nullable=False, doc="SLACK | DISCORD | WEBHOOK")
    url: Mapped[str] = mapped_column(String(1000), nullable=False)
    enabled: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    last_test_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    last_test_ok: Mapped[bool | None] = mapped_column(Boolean, nullable=True)
